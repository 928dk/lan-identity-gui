"""Generating, parsing and protecting the two files mac-rotator.sh reads.

Because the catalog owns membership and order, ``mac-list.txt`` and
``hostnamelist.txt`` are build artifacts.  A build artifact that a human can edit
is a drift trap, so every write here does three things:

1. renders the file from the catalog,
2. checks the file on disk against the hash of what this app last wrote,
3. backs up the previous content (last five kept) before replacing it.

When the hash does not match, the caller must ask: import the edit, overwrite, or
cancel.  Nothing is ever silently clobbered.

Rendering is deterministic: the same catalog produces the same bytes.  An earlier
draft stamped the generation time into the header, which made every regeneration
look like a change - harmless when a human pressed a button, actively wrong once a
timer can call ``--generate``.  The file's mtime carries the time; the header does
not.
"""

from __future__ import annotations

import difflib
import hashlib
import re
import shutil
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

from config import Settings

BACKUP_KEEP = 5

MAC_HEADER = """\
# MAC rotation list for mac-rotator.sh
# GENERATED by lan-identity-gui -- edit the rotation pool in the app, not here.
# This file is rewritten every time the pool changes in the app.
#
# Run the rotator with an empty prefix so stored names are used as-is:
#   ./mac-rotator.sh -f {mac_file} -H {host_file} -p ''
#
# One MAC per line, used in order and wrapping back to the top.
# Colons, dashes or bare hex are accepted; entries are normalized to
# 00:00:5E:00:53:01. Blank lines and # comments are ignored.
#
"""

HOST_HEADER = """\
# Hostname rotation list for mac-rotator.sh
# GENERATED by lan-identity-gui -- edit the hostname pool in the app, not here.
#
# Every entry below is a COMPLETE hostname (no prefix is added), so the rotator
# must be run with an empty prefix:
#   ./mac-rotator.sh -f {mac_file} -H {host_file} -p ''
#
# One label per line; used in order and wrapping back to the top.
# Blank lines and # comments are ignored.
#
"""

COMMENT_RE = re.compile(r"#.*$")


@dataclass
class WriteResult:
    path: Path
    wrote: bool
    drift: bool
    backup: Path | None
    previous_text: str
    new_text: str
    message: str

    @property
    def diff(self) -> str:
        return unified_diff(self.previous_text, self.new_text, str(self.path))


def render_mac_list(macs: list[str], settings: Settings) -> str:
    header = MAC_HEADER.format(
        mac_file=Path(settings.mac_list_path).name,
        host_file=Path(settings.hostname_list_path).name,
    )
    body = "\n".join(macs)
    return f"{header}\n{body}\n" if body else f"{header}\n"


def render_hostname_list(names: list[str], settings: Settings) -> str:
    header = HOST_HEADER.format(
        mac_file=Path(settings.mac_list_path).name,
        host_file=Path(settings.hostname_list_path).name,
    )
    body = "\n".join(names)
    return f"{header}\n{body}\n" if body else f"{header}\n"


def parse_mac_list(text: str) -> list[str]:
    found: list[str] = []
    for line in text.splitlines():
        cleaned = COMMENT_RE.sub("", line).strip()
        if not cleaned:
            continue
        found.append(cleaned)
    return found


def parse_hostname_list(text: str) -> list[str]:
    return parse_mac_list(text)


def digest(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def unified_diff(before: str, after: str, label: str = "") -> str:
    if before == after:
        return ""
    return "".join(
        difflib.unified_diff(
            before.splitlines(keepends=True),
            after.splitlines(keepends=True),
            fromfile=f"{label} (on disk)" if label else "before",
            tofile=f"{label} (generated)" if label else "after",
        )
    )


def _meta_key(path: Path) -> str:
    return f"export_hash:{path.name}"


def has_drift(path: Path, catalog) -> bool:
    """True when the file on disk is not what this app last wrote."""
    if not path.exists():
        return False
    recorded = catalog.get_meta(_meta_key(path))
    if not recorded:
        # Never written by the app: compare against the rendered planning state
        # is not possible here, so treat an unrecorded file as "please look".
        return True
    try:
        current = digest(path.read_text("utf-8", errors="replace"))
    except OSError:
        return False
    return current != recorded


def backup_path(path: Path, backup_dir: Path) -> Path:
    backup_dir.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    candidate = backup_dir / f"{path.name}.{stamp}.bak"
    counter = 1
    while candidate.exists():
        candidate = backup_dir / f"{path.name}.{stamp}-{counter}.bak"
        counter += 1
    return candidate


def prune_backups(path: Path, backup_dir: Path, keep: int = BACKUP_KEEP) -> list[Path]:
    if not backup_dir.exists():
        return []
    existing = sorted(backup_dir.glob(f"{path.name}.*.bak"), key=lambda p: p.name)
    removed: list[Path] = []
    while len(existing) > keep:
        victim = existing.pop(0)
        try:
            victim.unlink()
            removed.append(victim)
        except OSError:
            pass
    return removed


def write_file(
    path: Path,
    content: str,
    catalog,
    backup_dir: Path,
    force: bool = False,
) -> WriteResult:
    """Write ``content`` to ``path`` after the drift check and a backup."""
    previous = ""
    if path.exists():
        try:
            previous = path.read_text("utf-8", errors="replace")
        except OSError:
            previous = ""

    drifted = has_drift(path, catalog)
    if drifted and not force:
        return WriteResult(
            path=path, wrote=False, drift=True, backup=None,
            previous_text=previous, new_text=content,
            message=f"{path.name} changed on disk since the app last wrote it",
        )

    if previous == content and path.exists():
        # Nothing to change: record the hash so a stale meta entry heals.
        catalog.set_meta(_meta_key(path), digest(content))
        return WriteResult(
            path=path, wrote=False, drift=False, backup=None,
            previous_text=previous, new_text=content,
            message="already up to date",
        )

    saved: Path | None = None
    if path.exists():
        saved = backup_path(path, backup_dir)
        try:
            shutil.copy2(path, saved)
        except OSError:
            saved = None

    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(content, "utf-8")
    tmp.replace(path)
    catalog.set_meta(_meta_key(path), digest(content))
    if saved:
        prune_backups(path, backup_dir)

    return WriteResult(
        path=path, wrote=True, drift=False, backup=saved,
        previous_text=previous, new_text=content,
        message="written",
    )


def backups(path: Path, backup_dir: Path) -> list[Path]:
    if not backup_dir.exists():
        return []
    return sorted(backup_dir.glob(f"{path.name}.*.bak"), key=lambda p: p.name, reverse=True)


def export_both(catalog, settings: Settings, backup_dir: Path,
                force: bool = False) -> tuple[WriteResult, WriteResult]:
    """Regenerate both files.  Returns both results so the UI can show drift."""
    mac_path = Path(settings.mac_list_path)
    host_path = Path(settings.hostname_list_path)
    mac_result = write_file(
        mac_path, render_mac_list(catalog.pool_macs(), settings), catalog, backup_dir, force
    )
    host_result = write_file(
        host_path, render_hostname_list(catalog.pool_hostnames(), settings),
        catalog, backup_dir, force
    )
    return mac_result, host_result

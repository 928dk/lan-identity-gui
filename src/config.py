"""Configuration and well-known paths for lan-identity-gui.

Two directories, deliberately separate:

``~/.config/lan-identity-gui/``
    Settings the user may hand-edit: ``config.json``.

``~/.local/state/lan-identity-gui/``
    Everything derived or disposable: the catalog database, backups of the
    generated list files, written revert scripts and the apply log.

Nothing here requires root, and nothing here writes outside the user's home.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
from dataclasses import asdict, dataclass, field
from pathlib import Path

APP_NAME = "lan-identity-gui"
APP_TITLE = "LAN Identity"


def _app_home() -> Path:
    """Root for this app's own state.

    Normally the user's home. ``LAN_IDENTITY_HOME`` overrides it so a test run or
    an experiment cannot touch the real config, catalog or list files. The scripts
    this app drives (``~/scripts/mac-rotator.sh`` and friends) still resolve
    against the real home - they are not this app's state.
    """
    override = os.environ.get("LAN_IDENTITY_HOME", "").strip()
    if override:
        return Path(override).expanduser()
    return Path.home()


APP_HOME = _app_home()

CONFIG_DIR = APP_HOME / ".config" / APP_NAME
STATE_DIR = APP_HOME / ".local" / "state" / APP_NAME

CONFIG_PATH = CONFIG_DIR / "config.json"
CATALOG_PATH = STATE_DIR / "catalog.db"
EXPORT_DIR = STATE_DIR / "exports"
REVERT_DIR = STATE_DIR / "revert"
LOG_DIR = STATE_DIR / "logs"

#: Where the collector from packet 204 writes its append-only inventory.  That
#: file belongs to the collector, not to this app, so it deliberately follows the
#: real home even when LAN_IDENTITY_HOME redirects this app's own state.
INVENTORY_CSV = Path.home() / ".local" / "state" / "lan-mac-inventory" / "hosts.csv"

#: The two files mac-rotator.sh reads.  Generated by this app.
DEFAULT_MAC_LIST = Path.home() / "scripts" / "mac-list.txt"
DEFAULT_HOSTNAME_LIST = Path.home() / "scripts" / "hostnamelist.txt"

#: Local OUI databases, in order of preference.  Both ship with packages that
#: are already installed; no lookup ever leaves the machine.
OUI_SOURCES = (
    Path("/usr/share/nmap/nmap-mac-prefixes"),
    Path("/usr/share/arp-scan/ieee-oui.txt"),
)

#: Hostnames that belong to other machines on your network.  Adopting one is
#: legal but confusing, so the UI warns instead of blocking.  Deliberately empty
#: in the repository: a list of your machines is not something to publish, so you
#: fill it in ``config.json`` under ``"fleet_hostnames": ["…"]``.
DEFAULT_FLEET_HOSTNAMES: tuple[str, ...] = ()


def ensure_dirs() -> None:
    for path in (CONFIG_DIR, STATE_DIR, EXPORT_DIR, REVERT_DIR, LOG_DIR):
        path.mkdir(parents=True, exist_ok=True)


def default_interface() -> str:
    """Interface carrying the default route, else the first non-loopback one."""
    try:
        out = subprocess.run(
            ["ip", "route", "show", "default"],
            capture_output=True, text=True, timeout=5, check=False,
        ).stdout
        for line in out.splitlines():
            parts = line.split()
            if "dev" in parts:
                return parts[parts.index("dev") + 1]
    except (OSError, subprocess.SubprocessError):
        pass
    try:
        out = subprocess.run(
            ["ip", "-brief", "link", "show"],
            capture_output=True, text=True, timeout=5, check=False,
        ).stdout
        for line in out.splitlines():
            name = line.split()[0] if line.split() else ""
            if name and name != "lo" and not name.startswith(("docker", "veth", "virbr")):
                return name
    except (OSError, subprocess.SubprocessError):
        pass
    return "eth0"


def current_hostname() -> str:
    try:
        out = subprocess.run(
            ["hostnamectl", "--static"],
            capture_output=True, text=True, timeout=5, check=False,
        ).stdout.strip()
        if out:
            return out
    except (OSError, subprocess.SubprocessError):
        pass
    return os.uname().nodename


def own_mac(iface: str) -> str | None:
    """MAC currently burned into / spoofed onto ``iface``, canonical."""
    try:
        out = subprocess.run(
            ["ip", "-brief", "link", "show", "dev", iface],
            capture_output=True, text=True, timeout=5, check=False,
        ).stdout.split()
    except (OSError, subprocess.SubprocessError):
        return None
    for token in out:
        candidate = token.upper()
        if len(candidate) == 17 and candidate.count(":") == 5:
            return candidate
    return None


def own_ip(iface: str) -> str | None:
    """First IPv4 address on ``iface``, without the prefix length."""
    try:
        out = subprocess.run(
            ["ip", "-brief", "-4", "addr", "show", "dev", iface],
            capture_output=True, text=True, timeout=5, check=False,
        ).stdout
    except (OSError, subprocess.SubprocessError):
        return None
    for token in out.split():
        if token.count(".") == 3 and "/" in token:
            return token.split("/", 1)[0]
    return None


def have_carrier(iface: str) -> bool:
    path = Path(f"/sys/class/net/{iface}/carrier")
    try:
        return path.read_text().strip() == "1"
    except OSError:
        return False


@dataclass
class Settings:
    """Everything the rotation engine and the applier need to agree on."""

    iface: str = field(default_factory=default_interface)
    mac_list_path: str = str(DEFAULT_MAC_LIST)
    hostname_list_path: str = str(DEFAULT_HOSTNAME_LIST)
    catalog_path: str = str(CATALOG_PATH)
    inventory_path: str = str(INVENTORY_CSV)

    # Effective mac-rotator.sh options.
    hostname_prefix: str = ""
    rotate_hostname: bool = True
    interval: int = 1700
    down_wait: int = 10
    dhcp_wait: int = 60
    check_timeout: int = 30
    internet_check: bool = True
    dry_run: bool = True

    #: "independent" cycles each list on its own length (mac-rotator's behaviour),
    #: "paired" advances both together and wraps at the shorter list.
    pairing: str = "independent"

    #: Ask before the first write of the generated list files.
    first_export_confirmed: bool = False
    last_import_path: str = ""

    #: Other machines' hostnames, so a suggestion can warn when it would shadow
    #: one.  Kept out of the repository on purpose: it is your network, not the
    #: project's data.
    fleet_hostnames: list[str] = field(default_factory=list)

    def to_dict(self) -> dict:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: dict) -> "Settings":
        known = {f for f in cls.__dataclass_fields__}
        return cls(**{k: v for k, v in data.items() if k in known})

    @property
    def prefix_note(self) -> str:
        if self.hostname_prefix:
            return f'prefix "{self.hostname_prefix}" is applied on top of stored names'
        return 'prefix is empty — run mac-rotator.sh with -p \'\''


def load_settings() -> Settings:
    ensure_dirs()
    settings = Settings()
    if CONFIG_PATH.exists():
        try:
            settings = Settings.from_dict(json.loads(CONFIG_PATH.read_text("utf-8")))
        except (OSError, ValueError, TypeError):
            # A corrupt config must never stop the app from opening; the file is
            # left alone so the user can inspect it.
            shutil.copy2(CONFIG_PATH, CONFIG_PATH.with_suffix(".json.bad"))
    return settings


def save_settings(settings: Settings) -> None:
    ensure_dirs()
    tmp = CONFIG_PATH.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(settings.to_dict(), indent=2) + "\n", "utf-8")
    tmp.replace(CONFIG_PATH)
